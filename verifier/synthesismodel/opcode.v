  | 0x65 => JSGT_IMM
  | 0x75 => JSGE_IMM
  | 0xc5 => JSLT_IMM
  | 0xd5 => JSLE_IMM
  | 0x85 => CALL
  | 0x95 => EXIT

  | 0x1d => JEQ_REG
  | 0x2d => JGT_REG
  | 0x3d => JGE_REG
  | 0xad => JLT_REG
  | 0xbd => JLE_REG
  | 0x4d => JSET_REG
  | 0x5d => JNE_REG
  | 0x6d => JSGT_REG
  | 0x7d => JSGE_REG
  | 0xcd => JSLT_REG
  | 0xdd => JSLE_REG

  | _    => ILLGEL
  end.