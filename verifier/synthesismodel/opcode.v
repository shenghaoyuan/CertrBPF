Inductive opcode :=
  | ADD64_IMM | SUB64_IMM | MUL64_IMM | DIV64_IMM | OR64_IMM | AND64_IMM | LSH64_IMM
  | RSH64_IMM | NEG64     | MOD64_IMM | XOR64_IMM | MOV64_IMM | ARSH64_IMM
