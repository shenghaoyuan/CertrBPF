Definition nat2opcode (n:nat) : opcode :=
  match n with
  | 0x07 => ADD64_IMM
  | 0x17 => SUB64_IMM
  | 0x27 => MUL64_IMM
  | 0x37 => DIV64_IMM
  | 0x47 => OR64_IMM
  | 0x57 => AND64_IMM
  | 0x67 => LSH64_IMM
  | 0x77 => RSH64_IMM
  | 0x87 => NEG64
  | 0x97 => MOD64_IMM
  | 0xa7 => XOR64_IMM
  | 0xb7 => MOV64_IMM
  | 0xc7 => ARSH64_IMM

  | 0x0f => ADD64_REG
  | 0x1f => SUB64_REG
  | 0x2f => MUL64_REG
  | 0x3f => DIV64_REG
  | 0x4f => OR64_REG
  | 0x5f => AND64_REG
  | 0x6f => LSH64_REG
  | 0x7f => RSH64_REG
  | 0x9f => MOD64_REG
  | 0xaf => XOR64_REG
  | 0xbf => MOV64_REG
  | 0xcf => ARSH64_REG

  | 0x04 => ADD32_IMM
  | 0x14 => SUB32_IMM
  | 0x24 => MUL32_IMM
  | 0x34 => DIV32_IMM
  | 0x44 => OR32_IMM
  | 0x54 => AND32_IMM
  | 0x64 => LSH32_IMM
  | 0x74 => RSH32_IMM
  | 0x84 => NEG32
  | 0x94 => MOD32_IMM
  | 0xa4 => XOR32_IMM
  | 0xb4 => MOV32_IMM
  | 0xc4 => ARSH32_IMM

  | 0x0c => ADD32_REG
  | 0x1c => SUB32_REG
  | 0x2c => MUL32_REG
  | 0x3c => DIV32_REG
  | 0x4c => OR32_REG
  | 0x5c => AND32_REG
  | 0x6c => LSH32_REG
  | 0x7c => RSH32_REG
  | 0x9c => MOD32_REG
  | 0xac => XOR32_REG
  | 0xbc => MOV32_REG
  | 0xcc => ARSH32_REG

  | 0x18 => LDDW
  | 0x61 => LDXW
  | 0x69 => LDXH
  | 0x71 => LDXB
  | 0x79 => LDXDW
  | 0x62 => STW
  | 0x6a => STH
  | 0x72 => STB
  | 0x7a => STDW
  | 0x63 => STXW
  | 0x6b => STXH
  | 0x73 => STXB
  | 0x7b => STXDW

  | 0x05 => JA
  | 0x15 => JEQ_IMM
  | 0x25 => JGT_IMM
  | 0x35 => JGE_IMM
  | 0xa5 => JLT_IMM
  | 0xb5 => JLE_IMM
  | 0x45 => JSET_IMM
