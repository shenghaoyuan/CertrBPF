  | RSH64_REG | MOD64_REG | XOR64_REG | MOV64_REG | ARSH64_REG
  | ADD32_IMM | SUB32_IMM | MUL32_IMM | DIV32_IMM | OR32_IMM | AND32_IMM | LSH32_IMM
  | RSH32_IMM | NEG32     | MOD32_IMM | XOR32_IMM | MOV32_IMM | ARSH32_IMM
